package k6

import (
	"encoding/json"
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/youssefmahersi/ballast/internal/domain"
)

// GenerateScript writes the k6 script of a scenario graph.
//
// Deterministic: the same graph produces the same bytes, every time. The order
// comes from the graph's own steps and from sorting whatever a map holds, never
// from the order things were inserted.
//
// What it does not write is as important as what it does: no options block,
// because Ballast writes the load from the run's profile, and no secret, because
// a script is stored in the clear and read by whoever can see the project.
func GenerateScript(graph domain.ScenarioGraph) (string, error) {
	steps, err := graph.Steps()
	if err != nil {
		return "", err
	}

	script := &scriptWriter{indent: 1}
	script.preamble()

	for _, step := range steps {
		if err := script.step(step); err != nil {
			return "", err
		}
	}

	script.closing()

	return script.text.String(), nil
}

// scriptWriter builds the script line by line, keeping track of how deep it is.
type scriptWriter struct {
	text   strings.Builder
	indent int
}

// line writes one line at the current depth.
func (w *scriptWriter) line(format string, args ...any) {
	w.text.WriteString(strings.Repeat("  ", w.indent))
	fmt.Fprintf(&w.text, format, args...)
	w.text.WriteString("\n")
}

func (w *scriptWriter) preamble() {
	w.text.WriteString(`import http from "k6/http";
import { check, fail, sleep } from "k6";

// Generated by Ballast from a scenario graph. Editing this does nothing: the
// graph is what is stored, and this file is written from it again every time.
//
// No options block: Ballast writes the load from the run's profile, and k6
// reads it from the module it runs instead of this one.

const BASE_URL = __ENV.BASE_URL;

export default function () {
  const vars = {};
  let res = null;
`)
}

func (w *scriptWriter) closing() {
	w.text.WriteString("}\n")
}

// step writes one instruction of the flattened graph.
func (w *scriptWriter) step(step domain.Step) error {
	switch step.Kind {
	case domain.StepIf:
		condition, err := renderCondition(step.Node.Expression)
		if err != nil {
			return err
		}
		w.line("if (%s) {", condition)
		w.indent++

	case domain.StepElse:
		w.indent--
		w.line("} else {")
		w.indent++

	case domain.StepEndIf:
		w.indent--
		w.line("}")

	case domain.StepLoop:
		w.line("for (let i = 0; i < %d; i++) {", step.Node.Iterations)
		w.indent++

	case domain.StepEndLoop:
		w.indent--
		w.line("}")

	case domain.StepNode:
		return w.node(step.Node)

	default:
		return fmt.Errorf("the step kind %q cannot be written", step.Kind)
	}

	return nil
}

// node writes the one or two lines a node becomes.
func (w *scriptWriter) node(node domain.Node) error {
	switch node.Kind {
	case domain.NodeHTTPRequest:
		return w.request(node)

	case domain.NodeExtractVariable:
		w.line("vars[%s] = res ? res.json(%s) : null;",
			jsString(node.Variable), jsString(node.From))

	case domain.NodeSetVariable:
		return w.setVariable(node)

	case domain.NodeThinkTime:
		w.line("sleep(%s);", strconv.FormatFloat(node.Seconds, 'f', -1, 64))

	case domain.NodeAssertion:
		return w.assertion(node)

	case domain.NodeEnd:
		w.line("return;")

	default:
		return fmt.Errorf("the node kind %q cannot be written", node.Kind)
	}

	return nil
}

// request writes one HTTP call.
//
// http.request rather than http.get and its siblings: one shape for every
// method keeps this short, and k6 treats them the same.
func (w *scriptWriter) request(node domain.Node) error {
	url, err := urlExpression(node.Path)
	if err != nil {
		return err
	}

	// The tag is the path as it was written, never the address that was built.
	// With the real one, every identifier would become its own metric and a
	// threshold could not name an endpoint.
	tag := node.Method + " " + node.Path

	// Over several lines: this script is read by whoever wrote the scenario,
	// and a request with headers does not fit on one.
	body, err := requestBody(node)
	if err != nil {
		return err
	}

	headers, err := headersObject(node.Headers)
	if err != nil {
		return err
	}

	w.line("res = http.request(%s, %s, %s, {", jsString(node.Method), url, body)
	w.indent++
	w.line("headers: %s,", headers)
	w.line("tags: { name: %s },", jsString(tag))
	w.indent--
	w.line("});")

	if node.Critical {
		w.line("if (res.status >= 400) {")
		w.indent++
		w.line("fail(%s + res.status);", jsString(tag+" returned "))
		w.indent--
		w.line("}")
	}

	return nil
}

// assertion writes a check, and a fail when the step is critical.
func (w *scriptWriter) assertion(node domain.Node) error {
	condition, err := renderCondition(node.Expression)
	if err != nil {
		return err
	}

	w.line("const passed_%s = %s;", node.ID, condition)
	w.line("check(passed_%s, { %s: (ok) => ok });", node.ID, jsString(node.Expression))

	if node.Critical {
		w.line("if (!passed_%s) {", node.ID)
		w.indent++
		w.line("fail(%s);", jsString("the assertion "+node.ID+" did not hold"))
		w.indent--
		w.line("}")
	}

	return nil
}

// setVariable writes one variable: a literal, a value holding {{variables}}, or
// a secret read from the generator's environment.
func (w *scriptWriter) setVariable(node domain.Node) error {
	if node.FromEnv != "" {
		// Read at run time, so the secret itself is never in the script. The
		// fallback keeps an unset variable from becoming the text "undefined"
		// in a request.
		w.line("vars[%s] = __ENV[%s] || \"\";", jsString(node.Variable), jsString(node.FromEnv))
		return nil
	}

	value, err := textExpression(node.Value)
	if err != nil {
		return err
	}

	w.line("vars[%s] = %s;", jsString(node.Variable), value)
	return nil
}

// requestBody is what to send, or null for the methods that send nothing.
func requestBody(node domain.Node) (string, error) {
	if node.Body == "" {
		return "null", nil
	}
	return textExpression(node.Body)
}

// headersObject writes the headers, sorted by name so that two graphs that
// differ only in map order produce the same script.
func headersObject(headers map[string]string) (string, error) {
	if len(headers) == 0 {
		return "{}", nil
	}

	names := make([]string, 0, len(headers))
	for name := range headers {
		names = append(names, name)
	}
	sort.Strings(names)

	pairs := make([]string, 0, len(names))
	for _, name := range names {
		value, err := textExpression(headers[name])
		if err != nil {
			return "", err
		}
		pairs = append(pairs, jsString(name)+": "+value)
	}

	return "{ " + strings.Join(pairs, ", ") + " }", nil
}

// textExpression writes a header value or a body, where {{name}} reads a
// variable. Nothing is URL-encoded here: this is not an address.
func textExpression(text string) (string, error) {
	parts, err := domain.ParseTemplate(text)
	if err != nil {
		return "", err
	}

	if len(parts) == 0 {
		return jsString(""), nil
	}

	pieces := make([]string, 0, len(parts))
	for _, part := range parts {
		if part.Variable == "" {
			pieces = append(pieces, jsString(part.Text))
			continue
		}
		pieces = append(pieces, "vars["+jsString(part.Variable)+"]")
	}

	return strings.Join(pieces, " + "), nil
}

// urlExpression builds the address from the path template.
//
// A {name} in the path is a variable, and it goes through encodeURIComponent: a
// value holding a slash or a question mark would otherwise change which
// endpoint is called.
func urlExpression(path string) (string, error) {
	parts, err := domain.ParsePathTemplate(path)
	if err != nil {
		return "", err
	}

	pieces := []string{"BASE_URL"}
	for _, part := range parts {
		if part.Variable == "" {
			pieces = append(pieces, jsString(part.Text))
			continue
		}
		pieces = append(pieces, "encodeURIComponent(vars["+jsString(part.Variable)+"])")
	}

	return strings.Join(pieces, " + "), nil
}

// jsString turns any text into a JavaScript string literal.
//
// Through the JSON encoder, which is exactly the escaping a double-quoted
// JavaScript string needs: quotes, backslashes and line breaks all come back
// escaped. And a double-quoted string is not a template, so ${...} inside one
// is text and not a substitution -- which is why nothing here is ever written
// between backticks.
func jsString(text string) string {
	encoded, err := json.Marshal(text)
	if err != nil {
		// json.Marshal of a string fails on nothing a string can hold, but a
		// generator that silently wrote the raw text would be the one mistake
		// this function exists to prevent.
		return `"[unencodable]"`
	}
	return string(encoded)
}
