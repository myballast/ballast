// GenerateScript writes the k6 script of a scenario graph.
//
// Deterministic: the same graph produces the same bytes, every time. The order
// comes from the graph's own steps and from sorting whatever a map holds, never
// from the order things were inserted.
//
// What it does not write is as important as what it does: no options block,
// because Ballast writes the load from the run's profile, and no secret, because
// a script is stored in the clear and read by whoever can see the project.
func GenerateScript(graph domain.ScenarioGraph) (string, error) {
	steps, err := graph.Steps()
	if err != nil {
		return "", err
	}

	script := &scriptWriter{indent: 1}
	script.preamble()

	for _, step := range steps {
		if err := script.step(step); err != nil {
			return "", err
		}
	}

	script.closing()

	return script.text.String(), nil
}

// scriptWriter builds the script line by line, keeping track of how deep it is.
type scriptWriter struct {
	text   strings.Builder
	indent int
}

// line writes one line at the current depth.
func (w *scriptWriter) line(format string, args ...any) {
	w.text.WriteString(strings.Repeat("  ", w.indent))
	fmt.Fprintf(&w.text, format, args...)
	w.text.WriteString("\n")
}

func (w *scriptWriter) preamble() {
	w.text.WriteString(`import http from "k6/http";
import { check, fail, sleep } from "k6";

// Generated by Ballast from a scenario graph. Editing this does nothing: the
// graph is what is stored, and this file is written from it again every time.
//
// No options block: Ballast writes the load from the run's profile, and k6
// reads it from the module it runs instead of this one.

const BASE_URL = __ENV.BASE_URL;

export default function () {
  const vars = {};
  let res = null;
`)
}

func (w *scriptWriter) closing() {
	w.text.WriteString("}\n")
}

// step writes one instruction of the flattened graph.
func (w *scriptWriter) step(step domain.Step) error {
	switch step.Kind {
	case domain.StepIf:
		condition, err := renderCondition(step.Node.Expression)
		if err != nil {
			return err
		}
		w.line("if (%s) {", condition)
		w.indent++

	case domain.StepElse:
		w.indent--
		w.line("} else {")
		w.indent++

	case domain.StepEndIf:
		w.indent--
		w.line("}")

	case domain.StepLoop:
		w.loop(step.Node)

	case domain.StepEndLoop:
		w.indent--
		w.line("}")

	case domain.StepNode:
		return w.node(step.Node)

	default:
		return fmt.Errorf("the step kind %q cannot be written", step.Kind)
	}

	return nil
}

// node writes the one or two lines a node becomes.
func (w *scriptWriter) node(node domain.Node) error {
	switch node.Kind {
	case domain.NodeHTTPRequest:
		return w.request(node)

	case domain.NodeExtractVariable:
		w.extract(node)

	case domain.NodeSetVariable:
		return w.setVariable(node)

	case domain.NodeThinkTime:
		w.pause(node)

	case domain.NodeAssertion:
		return w.assertion(node)

	case domain.NodeEnd:
		w.line("return;")

	default:
		return fmt.Errorf("the node kind %q cannot be written", node.Kind)
	}

	return nil
}

// loop opens a loop. A count repeats that many times. A list takes its elements
// one at a time into the item variable, and never more than the maximum: the list
// came from somebody else's server, and the ceiling is what keeps one reply from
// deciding how long a run lasts.
//
// A variable that is not a list stops the iteration, with its name and not its
// content.
func (w *scriptWriter) loop(node domain.Node) {
	if node.Over == "" {
		w.line("for (let i = 0; i < %d; i++) {", node.Iterations)
		w.indent++
		return
	}

	list := "list_" + identifier(node.ID)
	w.line("const %s = vars[%s];", list, jsString(node.Over))
	w.line("if (!Array.isArray(%s)) {", list)
	w.indent++
	w.line("fail(%s);", jsString(fmt.Sprintf("the variable \"%s\" is not a list, so the loop cannot walk it", node.Over)))
	w.indent--
	w.line("}")
	w.line("for (let i = 0; i < Math.min(%s.length, %d); i++) {", list, node.Iterations)
	w.indent++
	w.line("vars[%s] = %s[i];", jsString(node.Item), list)
}

// pause waits a fixed time, or a time picked between two bounds.
func (w *scriptWriter) pause(node domain.Node) {
	if node.SecondsMax == 0 || node.SecondsMax == node.Seconds {
		w.line("sleep(%s);", strconv.FormatFloat(node.Seconds, 'f', -1, 64))
		return
	}

	w.line("sleep(%s + Math.random() * %s);",
		strconv.FormatFloat(node.Seconds, 'f', -1, 64),
		strconv.FormatFloat(node.SecondsMax-node.Seconds, 'f', -1, 64))
}

// identifier makes a node's id usable inside a JavaScript name. An id may hold a
// hyphen, which a name may not.
func identifier(id string) string {
	return strings.Map(func(r rune) rune {
		if r == '-' {
			return '_'
		}
		return r
	}, id)
}

// extract reads one value out of the last response, and stops the iteration when
// it is not there.
//
// Stopping is the point. A variable left empty would go into the next request as
// the text "null" or nothing at all, and the run would measure a call nobody meant
// to make — with a status that looks like the target's fault. fail() ends the
// iteration with a message that names the variable and where it was looked for,
// and never what the response held, which may be a token.
//
// The variable is set to null first, and each source only overwrites it when it
// finds something: a body that is not JSON, or no response at all, is the same
// "not found" as a missing key.
func (w *scriptWriter) extract(node domain.Node) {
	name := jsString(node.Variable)
	var where string

	w.line("vars[%s] = null;", name)

	switch node.Where() {
	case domain.ExtractFromHeader:
		// k6 spells a header as the server did, so the name is compared in lower
		// case on both sides.
		wanted := strings.TrimSpace(node.From)
		w.line("if (res) {")
		w.indent++
		w.line("for (const name in res.headers) {")
		w.indent++
		w.line("if (name.toLowerCase() === %s) {", jsString(strings.ToLower(wanted)))
		w.indent++
		w.line("vars[%s] = res.headers[name];", name)
		w.indent--
		w.line("}")
		w.indent--
		w.line("}")
		w.indent--
		w.line("}")
		where = "header " + wanted

	case domain.ExtractFromStatus:
		w.line("vars[%s] = res ? res.status : null;", name)
		where = "status"

	default:
		path := node.BodyPath()
		w.line("try {")
		w.indent++
		w.line("vars[%s] = res.json(%s);", name, jsString(path))
		w.indent--
		w.line("} catch (error) {")
		w.indent++
		w.line("vars[%s] = null;", name)
		w.indent--
		w.line("}")
		where = "body (" + path + ")"
	}

	w.line("if (vars[%s] === null || vars[%s] === undefined || vars[%s] === \"\") {", name, name, name)
	w.indent++
	w.line("fail(%s);", jsString(fmt.Sprintf("could not extract the variable \"%s\" from the response %s", node.Variable, where)))
	w.indent--
	w.line("}")
}

// request writes one HTTP call.
//
// http.request rather than http.get and its siblings: one shape for every
// method keeps this short, and k6 treats them the same.
func (w *scriptWriter) request(node domain.Node) error {
	url, err := urlExpression(node.Path)
	if err != nil {
		return err
	}

	query, err := queryExpression(node.Query)
	if err != nil {
		return err
	}
	url += query

	w.comment(node)

	// The tag is the path as it was written, never the address that was built.
	// With the real one, every identifier would become its own metric and a
	// threshold could not name an endpoint.
	tag := node.Method + " " + node.Path

	// Over several lines: this script is read by whoever wrote the scenario,
	// and a request with headers does not fit on one.
	body, err := requestBody(node)
	if err != nil {
		return err
	}

	headers, err := headersObject(node.Headers)
	if err != nil {
		return err
	}

	w.line("res = http.request(%s, %s, %s, {", jsString(node.Method), url, body)
	w.indent++
	w.line("headers: %s,", headers)
	w.line("tags: { name: %s },", jsString(tag))
	w.indent--
	w.line("});")

	if node.Critical {
		w.line("if (res.status >= 400) {")
		w.indent++
		w.line("fail(%s + res.status);", jsString(tag+" returned "))
		w.indent--
		w.line("}")
	}

	return nil
}

// comment writes where a node came from, when it says: the folder and the name
// its author gave it. They are text from somebody else's file, so they go on one
// comment line and nowhere else, with anything that could end the line turned
// into a space.
func (w *scriptWriter) comment(node domain.Node) {
	var parts []string
	for _, text := range []string{node.Group, node.Label} {
		if line := oneLine(text); line != "" {
			parts = append(parts, line)
		}
	}
	if len(parts) == 0 {
		return
	}
	w.line("// %s", strings.Join(parts, " / "))
}

// oneLine keeps text on a single line.
func oneLine(text string) string {
	return strings.TrimSpace(lineBreaks.ReplaceAllString(text, " "))
}

// lineBreaks are the characters JavaScript ends a line comment at.
var lineBreaks = regexp.MustCompile("[\\r\\n\u2028\u2029]+")

// queryExpression writes the query string: each name and value encoded as a
// component, in the order they were given. Nothing here depends on a map, so
// the same graph gives the same bytes.
func queryExpression(params []domain.QueryParam) (string, error) {
	if len(params) == 0 {
		return "", nil
	}

	pairs := make([]string, 0, len(params))
	for _, param := range params {
		value, err := textExpression(param.Value)
		if err != nil {
			return "", err
		}
		pairs = append(pairs, "encodeURIComponent("+jsString(param.Name)+") + \"=\" + encodeURIComponent("+value+")")
	}

	return " + \"?\" + " + strings.Join(pairs, " + \"&\" + "), nil
}

// assertion writes a check, and a fail when the step is critical.
func (w *scriptWriter) assertion(node domain.Node) error {
	condition, err := renderCondition(node.Expression)
	if err != nil {
		return err
	}

	name := "passed_" + identifier(node.ID)
	w.line("const %s = %s;", name, condition)
	w.line("check(%s, { %s: (ok) => ok });", name, jsString(node.Expression))

	if node.Critical {
		w.line("if (!%s) {", name)
		w.indent++
		w.line("fail(%s);", jsString("the assertion \""+node.Expression+"\" did not hold"))
		w.indent--
		w.line("}")
	}

	return nil
}

// setVariable writes one variable: a literal, a value holding {{variables}}, or
// a secret read from the generator's environment.
func (w *scriptWriter) setVariable(node domain.Node) error {
	if node.FromEnv != "" {
		// Read at run time, so the secret itself is never in the script. The
		// fallback keeps an unset variable from becoming the text "undefined"
		// in a request.
		w.line("vars[%s] = __ENV[%s] || \"\";", jsString(node.Variable), jsString(node.FromEnv))
		return nil
	}

	value, err := textExpression(node.Value)
	if err != nil {
		return err
	}

	w.line("vars[%s] = %s;", jsString(node.Variable), value)
	return nil
}

// requestBody is what to send, or null for the methods that send nothing.
func requestBody(node domain.Node) (string, error) {
	if node.Body == "" {
		return "null", nil
	}
	return textExpression(node.Body)
}

// headersObject writes the headers, sorted by name so that two graphs that
// differ only in map order produce the same script.
func headersObject(headers map[string]string) (string, error) {
	if len(headers) == 0 {
		return "{}", nil
	}

	names := make([]string, 0, len(headers))
	for name := range headers {
		names = append(names, name)
	}
	sort.Strings(names)

	pairs := make([]string, 0, len(names))
	for _, name := range names {
		value, err := textExpression(headers[name])
		if err != nil {
			return "", err
		}
		pairs = append(pairs, jsString(name)+": "+value)
	}

	return "{ " + strings.Join(pairs, ", ") + " }", nil
}

// textExpression writes a header value or a body, where {{name}} reads a
// variable. Nothing is URL-encoded here: this is not an address.
func textExpression(text string) (string, error) {
	parts, err := domain.ParseTemplate(text)
	if err != nil {
		return "", err
	}

	if len(parts) == 0 {
		return jsString(""), nil
	}

	pieces := make([]string, 0, len(parts))
	for _, part := range parts {
		if part.Variable == "" {
			pieces = append(pieces, jsString(part.Text))
			continue
		}
		pieces = append(pieces, "vars["+jsString(part.Variable)+"]")
	}

	// A value that is a variable and nothing else is made text: the status or a
	// number read from a body is a number, and a header or a body must be a string.
	// Beside a literal the + does it already.
	if len(parts) == 1 && parts[0].Variable != "" {
		return `"" + ` + pieces[0], nil
	}

	return strings.Join(pieces, " + "), nil
}

// urlExpression builds the address from the path template.
//
// A {name} in the path is a variable, and it goes through encodeURIComponent: a
// value holding a slash or a question mark would otherwise change which
// endpoint is called.
func urlExpression(path string) (string, error) {
	parts, err := domain.ParsePathTemplate(path)
	if err != nil {
		return "", err
	}

	pieces := []string{"BASE_URL"}
	for _, part := range parts {
		if part.Variable == "" {
			pieces = append(pieces, jsString(part.Text))
			continue
		}
		pieces = append(pieces, "encodeURIComponent(vars["+jsString(part.Variable)+"])")
	}

	return strings.Join(pieces, " + "), nil
}

// jsString turns any text into a JavaScript string literal.
//
// Through the JSON encoder, which is exactly the escaping a double-quoted
// JavaScript string needs: quotes, backslashes and line breaks all come back
// escaped. And a double-quoted string is not a template, so ${...} inside one
// is text and not a substitution -- which is why nothing here is ever written
// between backticks.
func jsString(text string) string {
	encoded, err := json.Marshal(text)
	if err != nil {
		// json.Marshal of a string fails on nothing a string can hold, but a
		// generator that silently wrote the raw text would be the one mistake
		// this function exists to prevent.
		return `"[unencodable]"`
	}
	return string(encoded)
}

// Generator writes graph scenarios as k6 scripts. It holds no state; it exists
// so that the usecase can depend on an interface it declares, with the function
// above behind it.
type Generator struct{}

// NewGenerator returns a generator.
func NewGenerator() Generator {
	return Generator{}
}

// Generate writes the script of a graph.
func (Generator) Generate(graph domain.ScenarioGraph) (string, error) {
	return GenerateScript(graph)
}
