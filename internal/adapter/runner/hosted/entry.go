package hosted

import (
	"encoding/json"
	"fmt"
	"strings"
)

// entryTemplate is the module k6 actually runs. The user's script is imported,
// never executed directly, and that is what makes the load ceilings binding.
//
// k6 reads options from its entry module and from nowhere else. A user script
// that declares its own — 500 virtual users for an hour, a threshold that can
// never fail — is simply not consulted: its options export is dead code rather
// than something we have to detect and strip. There is no precedence to reason
// about and no JavaScript to parse.
//
// It is silent, though, so the user is told at import time instead, where the
// message can reach them.
//
// setup and teardown are wrapped rather than re-exported because a named
// re-export of something the script does not define fails to compile. Going
// through the namespace object works whatever the script declares.
const entryTemplate = `// Generated by Ballast. Do not edit.
import * as user from './%s';

export const options = %s;

export function setup() {
	return user.setup ? user.setup() : undefined;
}

export function teardown(data) {
	if (user.teardown) {
		user.teardown(data);
	}
}

export default function (data) {
	return user.default(data);
}

export function handleSummary(data) {
	return { %s: JSON.stringify(data) };
}
`

// buildEntryScript renders the entry module around a set of k6 options.
func buildEntryScript(options []byte) (string, error) {
	if !json.Valid(options) {
		return "", fmt.Errorf("%w: the k6 options are not valid JSON", ErrInvalidJob)
	}

	// The options come from our own marshaller and the summary path is a
	// constant, but both are rendered as JSON string literals rather than
	// pasted in, so that nothing a user typed into a threshold expression can
	// end up read as code.
	path, err := json.Marshal(summaryPath)
	if err != nil {
		return "", fmt.Errorf("render the summary path: %w", err)
	}

	return fmt.Sprintf(entryTemplate, userScriptName, strings.TrimSpace(string(options)), path), nil
}
