#!/usr/bin/env bash
#
# Writes ballast.gitlab-ci.yml, the file a GitLab project includes, from the two scripts
# next to it and the VERSION file. The template carries the scripts inside it, so that
# one file is all there is to include, and to trust: an `include:` cannot depend on a
# second repository. A test regenerates it and compares: edit the scripts, run this, and
# commit both.
#
#   ops/gitlab/generate.sh > ops/gitlab/ballast.gitlab-ci.yml

set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

version="$(tr -d ' \r\n' < "$here/VERSION")"

# The image is pinned by digest: what a job runs in must not change without a commit.
image="alpine:3.21@sha256:bc21487101ae47172509130ee1092cc273a831968d64b617776d1f69c81e42ab"

# embed writes a script as the body of a quoted here-document, indented as the YAML
# block that holds it. The end marker must not be in the script.
embed() {
  local marker="$1" file="$2"
  if grep -q "^${marker}\$" "$file"; then
    echo "generate.sh: $file contains its own end marker" >&2
    exit 1
  fi
  echo "      cat > \"\$dir/$(basename "$file")\" <<'${marker}'"
  sed 's/^\(.\)/      \1/' "$file"
  echo "      ${marker}"
}

cat <<YAML
# Ballast load test, for GitLab CI.
#
# Generated by ops/gitlab/generate.sh from install.sh, run.sh and VERSION: do not edit it
# by hand. Include it, and set the variables below in your project:
#
#   include:
#     - remote: https://raw.githubusercontent.com/myballast/ballast/<tag>/ops/gitlab/ballast.gitlab-ci.yml
#
# Variables (Settings > CI/CD > Variables):
#   BALLAST_TOKEN           an API token of the project. Masked and protected, never written
#                           in a file. Required.
#   BALLAST_URL             the address of your Ballast. Required.
#   BALLAST_SCENARIO_ID     the scenario to run (a UUID). Required.
#   BALLAST_ENVIRONMENT_ID  the environment to run against (a UUID). Required.
#   BALLAST_PROFILE         smoke, load, stress, spike or soak. Required.
#   BALLAST_TIMEOUT         how long to give the run from its launch, for example 90m.
#   BALLAST_QUEUE_TIMEOUT   how long to wait when a limit was reached, for example 20m.
#   BALLAST_ALLOW_NO_THRESHOLD, BALLAST_NO_FAIL_ON_BREACH   true or false.
#   BALLAST_VERSION         the version of the command, default the one of this file.

.ballast-run:
  image: ${image}
  variables:
    BALLAST_VERSION: ${version}
  script:
    - |
      set -eu
      if ! command -v bash >/dev/null 2>&1 || ! command -v curl >/dev/null 2>&1; then
        apk add --no-cache bash curl >/dev/null
      fi
      dir="\$(mktemp -d)"
YAML
embed BALLAST_INSTALL_SCRIPT "$here/install.sh"
embed BALLAST_RUN_SCRIPT "$here/run.sh"
cat <<'YAML'
      BALLAST_BIN="$(bash "$dir/install.sh")"
      export BALLAST_BIN
      exec bash "$dir/run.sh"

ballast-load-test:
  extends: .ballast-run
  stage: test
YAML
